#!/usr/bin/env node
/**
 * Builds the Google Apps Script version into apps-script/dist/:
 *
 *   node scripts/build_gas.js        (or: npm run gas:build)
 *
 * Apps Script only takes .gs and .html files and has no folders, so this:
 *   - copies apps-script/src (Code.gs) and writes appsscript.json
 *   - generates Places.gs: the map's building names (dropdown + validation)
 *   - turns webmap/index.html into Map.html and bundles its ~120 script files,
 *     in their original order, into a few JsN.html includes
 *     (OpenLayers itself loads from the jsDelivr CDN)
 *   - embeds the legend icons, switches the satellite tiles to https
 *   - turns admin/ into Admin.html + AdminJs.html + AdminCss.html
 *
 * Env GAS_ACCESS: ANYONE_ANONYMOUS (default: anyone, no Google login needed)
 *                 DOMAIN (only accounts in your Google Workspace domain)
 *                 ANYONE (anyone signed in to a Google account)
 */
const fs = require('fs');
const path = require('path');
const { ROOT, WEBMAP, loadPlaces } = require('./lib');

const SRC = path.join(ROOT, 'apps-script', 'src');
const DIST = path.join(ROOT, 'apps-script', 'dist');
const ADMIN = path.join(ROOT, 'admin');
const OL_VERSION = '10.7.0';
const OL_JS = `https://cdn.jsdelivr.net/npm/ol@${OL_VERSION}/dist/ol.js`;
const OL_CSS = `https://cdn.jsdelivr.net/npm/ol@${OL_VERSION}/ol.css`;
const BUNDLE_LIMIT = 350 * 1024;
const ACCESS = process.env.GAS_ACCESS || 'ANYONE_ANONYMOUS';
if (!['ANYONE_ANONYMOUS', 'ANYONE', 'DOMAIN'].includes(ACCESS)) throw new Error('GAS_ACCESS must be ANYONE_ANONYMOUS, ANYONE or DOMAIN');

const read = p => fs.readFileSync(p, 'utf8');
const scriptTag = code => '<script>\n' + code.replace(/<\/script/gi, '<\\/script') + '\n</script>\n';
const styleTag = css => '<style>\n' + css + '\n</style>\n';
const round = g => JSON.parse(JSON.stringify(g), (k, v) => (typeof v === 'number' && !Number.isInteger(v) ? Math.round(v * 1e7) / 1e7 : v));

/** Round coordinates in a qgis2web layer file ("var json_X = {...};") to ~1 cm. */
function compactLayer(code) {
  const i = code.indexOf('=');
  const json = JSON.parse(code.slice(i + 1).trim().replace(/;\s*$/, ''));
  return code.slice(0, i).trim() + ' = ' + JSON.stringify(round(json)) + ';';
}

/** Template config: values are HTML-escaped by <?= ?> and read back from data- attributes. */
const CONFIG_HTML =
  '<div id="ppe-cfg" hidden data-base="<?= baseUrl ?>" data-building="<?= building ?>"></div>\n' +
  '<script>(function(){var c=document.getElementById("ppe-cfg");' +
  'window.PPE_BASE_URL=c.getAttribute("data-base");window.PPE_START_BUILDING=c.getAttribute("data-building")||"";})();</script>\n';

function build() {
  fs.rmSync(DIST, { recursive: true, force: true });
  fs.mkdirSync(DIST, { recursive: true });
  const files = {};

  // ---- server code -----------------------------------------------------------
  for (const f of fs.readdirSync(SRC)) files[f] = read(path.join(SRC, f));
  const places = loadPlaces();
  files['Places.gs'] = '// Generated by scripts/build_gas.js from the map - do not edit.\n' +
    'var PLACES = ' + JSON.stringify(places.map(p => ({ key: p.key, layer: p.layerTitle }))) + ';\n';
  files['appsscript.json'] = JSON.stringify({
    timeZone: 'Asia/Thimphu',
    dependencies: { enabledAdvancedServices: [{ userSymbol: 'Drive', serviceId: 'drive', version: 'v3' }] },
    webapp: { executeAs: 'USER_DEPLOYING', access: ACCESS },
    exceptionLogging: 'STACKDRIVER',
    runtimeVersion: 'V8',
    oauthScopes: [
      'https://www.googleapis.com/auth/spreadsheets',
      'https://www.googleapis.com/auth/drive',
      'https://www.googleapis.com/auth/script.external_request',
    ],
  }, null, 2) + '\n';

  // ---- map: stylesheets --------------------------------------------------------
  let html = read(path.join(WEBMAP, 'index.html'));
  let css = '';
  html = html.replace(/[ \t]*<link rel="stylesheet" href="\.?\/?([^"]+)">\s*\n?/g, (m, href) => {
    if (/(^|\/)ol\.css$/.test(href)) return `    <link rel="stylesheet" href="${OL_CSS}">\n`;
    if (/fontawesome/.test(href)) return ''; // its font files don't exist on the original site either
    css += `/* ${href} */\n` + read(path.join(WEBMAP, href)) + '\n';
    return '';
  });
  files['Css.html'] = styleTag(css);
  html = html.replace('</head>', "    <?!= include('Css') ?>\n  </head>");

  // ---- map: scripts -> ordered pieces -> bundles ---------------------------------
  const legend = {};
  for (const f of fs.readdirSync(path.join(WEBMAP, 'styles', 'legend'))) {
    legend['styles/legend/' + f] = 'data:image/png;base64,' + fs.readFileSync(path.join(WEBMAP, 'styles', 'legend', f)).toString('base64');
  }
  const start = html.search(/<script[\s>]/);
  const end = html.lastIndexOf('</script>') + '</script>'.length;
  const pieces = [];
  for (const m of html.slice(start, end).matchAll(/<script(?:\s+src="([^"]+)")?[^>]*>([\s\S]*?)<\/script>/g)) {
    const src = m[1];
    if (!src) { pieces.push({ code: m[2] }); continue; }
    const rel = src.replace(/^\.\//, '');
    if (rel === 'resources/ol.js') { pieces.push({ cdn: OL_JS }); continue; }
    let code = read(path.join(WEBMAP, rel));
    if (/^layers\/(?!layers\.js$)/.test(rel)) code = compactLayer(code);
    if (rel === 'layers/layers.js') {
      code = code.replace(/http:\/\/mt0\.google\.com/g, 'https://mt0.google.com')
        .replace(/styles\/legend\/[^"']+\.png/g, p => legend[p] || p);
    }
    if (rel === 'inventory/inventory_data.js') {
      // Assets are loaded live from the Google Sheet; ship only the building shapes.
      code = 'window.INVENTORY_DATA = ' + JSON.stringify({
        generated: new Date().toISOString(),
        places: places.map(p => ({ key: p.key, layer: p.layerTitle, c: p.centroid && round(p.centroid), g: round(p.geometry) })),
        items: [],
      }) + ';';
    }
    pieces.push({ code: `/* ${rel} */\n${code}` });
  }

  const tags = [];
  let bundle = '', n = 0;
  const flush = () => {
    if (!bundle) return;
    n++;
    files[`Js${n}.html`] = scriptTag(bundle);
    tags.push(`<?!= include('Js${n}') ?>`);
    bundle = '';
  };
  for (const p of pieces) {
    if (p.cdn) { flush(); tags.push(`<script src="${p.cdn}"></script>`); continue; }
    if (bundle && bundle.length + p.code.length > BUNDLE_LIMIT) flush();
    bundle += p.code + '\n;\n';
  }
  flush();
  // Config must exist before the inventory overlay runs: put it before all scripts.
  files['Map.html'] = html.slice(0, start) + CONFIG_HTML + '    ' + tags.join('\n    ') + html.slice(end);

  // ---- admin ------------------------------------------------------------------
  let admin = read(path.join(ADMIN, 'index.html'));
  files['AdminCss.html'] = styleTag(read(path.join(ADMIN, 'admin.css')));
  files['AdminJs.html'] = scriptTag(read(path.join(ADMIN, 'admin.js')));
  admin = admin.replace('<link rel="stylesheet" href="admin.css">', "<?!= include('AdminCss') ?>")
    .replace('<script src="admin.js"></script>', CONFIG_HTML + "<?!= include('AdminJs') ?>")
    .replace('href="/api/excel"', 'href="#"');
  files['Admin.html'] = admin;

  // ---- write + sanity checks ----------------------------------------------------------
  for (const [name, content] of Object.entries(files)) {
    if (/\.html$/.test(name) && !['Map.html', 'Admin.html'].includes(name) && content.includes('<?')) {
      // Included files are inserted raw, so this is harmless, but flag it.
      console.warn(`note: ${name} contains "<?" (fine for include(), not for templates)`);
    }
    fs.writeFileSync(path.join(DIST, name), content);
  }
  for (const t of ['Map.html', 'Admin.html']) {
    const scriptlets = (files[t].match(/<\?/g) || []).length;
    const closes = (files[t].match(/\?>/g) || []).length;
    if (scriptlets !== closes) throw new Error(`${t}: unbalanced template tags`);
  }
  return files;
}

if (require.main === module) {
  const files = build();
  const kb = s => (Buffer.byteLength(s) / 1024).toFixed(0) + ' KB';
  console.log(`Built apps-script/dist (web app access: ${ACCESS}):`);
  for (const [name, c] of Object.entries(files)) console.log(`  ${name.padEnd(18)} ${kb(c)}`);
  const total = Object.values(files).reduce((s, c) => s + Buffer.byteLength(c), 0);
  console.log(`  total              ${(total / 1024).toFixed(0)} KB`);
}
module.exports = { build };
